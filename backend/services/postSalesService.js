/**
 * 3. File Customer Complaint
 */
export const fileCustomerComplaint = async (complaintData, user) => {
  const client = await Client.findById(complaintData.clientId);
  if (!client) {
    const error = new Error(`Client not found with ID: ${complaintData.clientId}`);
    error.statusCode = 404;
    throw error;
  }

  const complaintCode = complaintData.complaintCode || (await generateComplaintCode());

  // Calculate SLA target resolution date
  let targetDate = complaintData.targetResolutionDate ? new Date(complaintData.targetResolutionDate) : new Date();
  if (!complaintData.targetResolutionDate) {
    switch (complaintData.severity) {
      case 'critical_brand_emergency':
        targetDate.setHours(targetDate.getHours() + 4);
        break;
      case 'high_safety_or_electrical':
        targetDate.setHours(targetDate.getHours() + 24);
        break;
      case 'medium_functional_glitch':
        targetDate.setHours(targetDate.getHours() + 48);
        break;
      case 'low_minor_cosmetic':
      default:
        targetDate.setDate(targetDate.getDate() + 5);
        break;
    }
  }

  const complaint = await CustomerComplaint.create({
    complaintCode,
    clientId: client._id,
    jobOrderId: complaintData.jobOrderId || null,
    siteInstallationId: complaintData.siteInstallationId || null,
    reportedByClientContact: complaintData.reportedByClientContact || {
      fullName: client.displayName,
      phone: client.primaryPhone
    },
    reportedDate: complaintData.reportedDate ? new Date(complaintData.reportedDate) : new Date(),
    category: complaintData.category || 'installation_workmanship',
    severity: complaintData.severity || 'medium_functional_glitch',
    status: 'logged_open',
    complaintSubject: complaintData.complaintSubject,
    detailedDescription: complaintData.detailedDescription,
    targetResolutionDate: targetDate,
    evidencePhotoId: complaintData.evidencePhotoId || null
  });

  return complaint;
};

