/**
 * 7. Process Warranty Claim
 * Validates coverage against JobOrder.warranty subdocument:
 * - warranty.status === 'active_under_warranty' and !isVoided
 * - claimDate <= expirationDeadlines[failedComponentExpiry]
 * If valid: approved_full_parts_and_labor and auto-drafts StaffRequest for replacement parts!
 */
export const processWarrantyClaim = async (claimData, user) => {
  const jobOrder = await JobOrder.findById(claimData.jobOrderId);
  if (!jobOrder) {
    const error = new Error(`JobOrder not found with ID: ${claimData.jobOrderId}`);
    error.statusCode = 404;
    throw error;
  }

  const claimCode = claimData.claimCode || (await generateClaimCode());
  const claimDate = claimData.claimDate ? new Date(claimData.claimDate) : new Date();

  // Evaluate Coverage Against JobOrder.warranty
  const warranty = jobOrder.warranty;
  let isCovered = false;
  let determination = 'rejected_out_of_warranty';
  let rejectionReasonNotes = '';

  if (!warranty || warranty.status !== 'active_under_warranty') {
    isCovered = false;
    determination = 'rejected_out_of_warranty';
    rejectionReasonNotes = `JobOrder warranty is not active (current status: ${warranty?.status || 'none'}).`;
  } else if (warranty.isVoided) {
    isCovered = false;
    determination = 'rejected_unauthorized_tampering';
    rejectionReasonNotes = `Warranty has been voided: ${warranty.voidReason || 'Contractual breach'}`;
  } else {
    // Check component expiration deadline
    const deadlines = warranty.expirationDeadlines || {};
    let deadline = null;

    switch (claimData.failedComponent) {
      case 'power_supply_transformer':
        deadline = deadlines.transformerExpiry;
        break;
      case 'silicone_neon_flex':
        deadline = deadlines.neonFlexExpiry;
        break;
      case 'led_modules':
        deadline = deadlines.ledModulesExpiry;
        break;
      case 'acrylic_face_or_letter':
      case 'structural_frame_or_bracket':
      case 'wiring_connection':
      default:
        deadline = deadlines.structuralExpiry;
        break;
    }

    if (deadline && claimDate.getTime() <= new Date(deadline).getTime()) {
      isCovered = true;
      determination = 'approved_full_parts_and_labor';
    } else {
      isCovered = false;
      determination = 'rejected_out_of_warranty';
      rejectionReasonNotes = `Component coverage deadline passed on ${deadline ? new Date(deadline).toISOString() : 'N/A'}`;
    }
  }

  let evaluator = claimData.evaluatedBy;
  if (!evaluator && user?.email) {
    const emp = await Employee.findOne({ email: user.email });
    if (emp) evaluator = emp._id;
  }

  const warrantyClaim = await WarrantyClaim.create({
    claimCode,
    jobOrderId: jobOrder._id,
    jobOrderNumber: jobOrder.jobOrderNumber,
    clientId: claimData.clientId || jobOrder.clientId,
    claimDate,
    status: isCovered ? 'claim_approved' : 'claim_rejected',
    failedComponent: claimData.failedComponent,
    defectDescription: claimData.defectDescription,
    evidenceMediaId: claimData.evidenceMediaId || null,
    evaluatedBy: evaluator || null,
    evaluationDate: new Date(),
    isCoveredUnderActiveWarranty: isCovered,
    determination,
    rejectionReasonNotes,
    fulfillment: claimData.fulfillment || {}
  });

  let storeStaffRequest = null;

  // Auto-draft zero-cost Store StaffRequest if components specified and approved
  if (isCovered && claimData.componentsNeeded && claimData.componentsNeeded.length > 0) {
    const staffRequestItems = claimData.componentsNeeded.map((item) => {
      const qty = item.quantity || 1;
      return {
        stockItemId: item.stockItemId || new mongoose.Types.ObjectId(),
        itemName: item.itemName,
        requestedQuantity: qty,
        requestedTotalQuantity: qty,
        approvedQuantity: qty,
        approvedTotalQuantity: qty,
        unit: 'pcs',
        baseUnit: 'pcs',
        multiplierNumerator: 1,
        multiplierDenominator: 1,
        multiplier: 1,
        approvalStatus: 'approved',
        purpose: `Warranty Claim Fulfillment for ${jobOrder.jobOrderNumber}`
      };
    });

    const totalQty = staffRequestItems.reduce((sum, i) => sum + i.requestedQuantity, 0);

    storeStaffRequest = await StaffRequest.create({
      requestCode: `WREQ-${claimCode}`,
      requestType: 'workshop',
      requestedBy: user?._id || new mongoose.Types.ObjectId(),
      departmentId: jobOrder.workstationRouting?.electricalAndQC?.inspectorId || new mongoose.Types.ObjectId(),
      jobOrderId: jobOrder._id,
      jobOrderNumber: jobOrder.jobOrderNumber,
      items: staffRequestItems,
      totalItems: staffRequestItems.length,
      totalRequestedQuantity: totalQty,
      totalApprovedQuantity: totalQty,
      approvalStatus: 'approved',
      purpose: `Zero-cost replacement materials authorized under Warranty Claim ${claimCode}`,
      approvalDetails: {
        isApproved: true,
        approvedBy: user?._id || null,
        approvalDate: new Date()
      },
      notes: `Zero-cost replacement materials authorized under Warranty Claim ${claimCode}`
    });

    warrantyClaim.fulfillment.storeStaffRequestId = storeStaffRequest._id;
    await warrantyClaim.save();
  }

  return { warrantyClaim, storeStaffRequest };
};

/**
 * 8. Fulfill Warranty Claim
 */
export const fulfillWarrantyClaim = async (claimId, fulfillmentData, user) => {
  const claim = await WarrantyClaim.findById(claimId);
  if (!claim) {
    const error = new Error(`Warranty claim not found with ID: ${claimId}`);
    error.statusCode = 404;
    throw error;
  }

  let tech = fulfillmentData.dispatchedTechnician;
  if (!tech && user?.email) {
    const emp = await Employee.findOne({ email: user.email });
    if (emp) tech = emp._id;
  }

  claim.fulfillment = {
    ...claim.fulfillment,
    dispatchedTechnician: tech || claim.fulfillment?.dispatchedTechnician || null,
    repairExecutionDate: fulfillmentData.repairExecutionDate ? new Date(fulfillmentData.repairExecutionDate) : new Date(),
    componentsReplaced: fulfillmentData.componentsReplaced || claim.fulfillment?.componentsReplaced || [],
    claimResolutionCostETB: Number(fulfillmentData.claimResolutionCostETB || claim.fulfillment?.claimResolutionCostETB || 0)
  };

  if (fulfillmentData.clientHandoverSignOff) {
    claim.clientHandoverSignOff = {
      isSatisfactorilyRepaired: Boolean(fulfillmentData.clientHandoverSignOff.isSatisfactorilyRepaired),
      clientWitnessName: fulfillmentData.clientHandoverSignOff.clientWitnessName || '',
      clientSignatureUrl: fulfillmentData.clientHandoverSignOff.clientSignatureUrl || '',
      signOffDate: new Date(),
      afterRepairPhotoEvidenceId: fulfillmentData.clientHandoverSignOff.afterRepairPhotoEvidenceId || null
    };

    if (claim.clientHandoverSignOff.isSatisfactorilyRepaired) {
      claim.status = 'closed';
    } else {
      claim.status = 'repaired_on_site';
    }
  } else {
    claim.status = fulfillmentData.status || 'repaired_on_site';
  }

  await claim.save();
  return claim;
};

