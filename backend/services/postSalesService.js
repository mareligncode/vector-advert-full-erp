/**
 * 10. Customer Feedback & Quality Metrics
 */
export const getFeedbackMetrics = async () => {
  const feedbacks = await CustomerFeedback.find();
  const totalFeedbacks = feedbacks.length;

  let promoters = 0;
  let passives = 0;
  let detractors = 0;
  let totalScore = 0;

  for (const f of feedbacks) {
    totalScore += f.ratings?.overallSatisfactionScore || 0;
    if (f.npsCategory === 'promoter') promoters++;
    else if (f.npsCategory === 'passive') passives++;
    else if (f.npsCategory === 'detractor') detractors++;
  }

  const avgSatisfaction = totalFeedbacks > 0 ? Number((totalScore / totalFeedbacks).toFixed(2)) : 0;
  const npsScore = totalFeedbacks > 0 ? Number((((promoters - detractors) / totalFeedbacks) * 100).toFixed(1)) : 0;

  const totalComplaints = await CustomerComplaint.countDocuments();
  const openComplaints = await CustomerComplaint.countDocuments({ status: { $ne: 'closed_satisfied' } });

  const totalClaims = await WarrantyClaim.countDocuments();
  const approvedClaims = await WarrantyClaim.countDocuments({ isCoveredUnderActiveWarranty: true });

  return {
    totalFeedbacks,
    averageSatisfactionScore: avgSatisfaction,
    netPromoterScore: npsScore,
    npsBreakdown: {
      promoters,
      passives,
      detractors
    },
    complaintMetrics: {
      totalComplaints,
      openComplaints,
      resolutionRate: totalComplaints > 0 ? Number((((totalComplaints - openComplaints) / totalComplaints) * 100).toFixed(1)) : 100
    },
    warrantyMetrics: {
      totalClaims,
      approvedClaims,
      approvalRate: totalClaims > 0 ? Number(((approvedClaims / totalClaims) * 100).toFixed(1)) : 100
    }
  };
};
