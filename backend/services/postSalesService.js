/**
 * Auto-generate code helpers
 */
const generateFeedbackCode = async () => {
  const year = new Date().getFullYear();
  const count = await CustomerFeedback.countDocuments();
  return `FDB-${year}-${String(count + 1).padStart(4, '0')}`;
};

const generateComplaintCode = async () => {
  const year = new Date().getFullYear();
  const count = await CustomerComplaint.countDocuments();
  return `CMP-${year}-${String(count + 1).padStart(4, '0')}`;
};

const generateClaimCode = async () => {
  const year = new Date().getFullYear();
  const count = await WarrantyClaim.countDocuments();
  return `CLM-${year}-${String(count + 1).padStart(4, '0')}`;
};

/**
 * 1. Record Customer Feedback
 * Rule 3 Detractor Escalation: If overallSatisfactionScore <= 2,
 * sets requiresManagementFollowUp = true and auto-generates a high-priority CustomerComplaint ticket!
 */
export const recordCustomerFeedback = async (feedbackData, user) => {
  const client = await Client.findById(feedbackData.clientId);
  if (!client) {
    const error = new Error(`Client not found with ID: ${feedbackData.clientId}`);
    error.statusCode = 404;
    throw error;
  }

  const jobOrder = await JobOrder.findById(feedbackData.jobOrderId);
  if (!jobOrder) {
    const error = new Error(`JobOrder not found with ID: ${feedbackData.jobOrderId}`);
    error.statusCode = 404;
    throw error;
  }

  const feedbackCode = feedbackData.feedbackCode || (await generateFeedbackCode());

  // Determine NPS Category
  let npsCategory = feedbackData.npsCategory;
  const npsScore = feedbackData.npsScore !== undefined ? Number(feedbackData.npsScore) : undefined;
  if (npsScore !== undefined && !npsCategory) {
    if (npsScore >= 9) npsCategory = 'promoter';
    else if (npsScore >= 7) npsCategory = 'passive';
    else npsCategory = 'detractor';
  }

  let collectedBy = feedbackData.collectedBy;
  if (!collectedBy && user?.email) {
    const emp = await Employee.findOne({ email: user.email });
    if (emp) collectedBy = emp._id;
  }

  const overallScore = Number(feedbackData.ratings?.overallSatisfactionScore || 5);
  const isDetractor = overallScore <= 2 || npsCategory === 'detractor';

  const feedback = await CustomerFeedback.create({
    feedbackCode,
    clientId: client._id,
    jobOrderId: jobOrder._id,
    clientOrderId: feedbackData.clientOrderId || jobOrder.orderId || null,
    siteInstallationId: feedbackData.siteInstallationId || null,
    collectedBy: collectedBy || null,
    channel: feedbackData.channel || 'in_person_handover',
    submissionDate: feedbackData.submissionDate ? new Date(feedbackData.submissionDate) : new Date(),
    ratings: {
      overallSatisfactionScore: overallScore,
      designFidelityRating: feedbackData.ratings?.designFidelityRating,
      illuminationBrightnessRating: feedbackData.ratings?.illuminationBrightnessRating,
      installationWorkmanshipRating: feedbackData.ratings?.installationWorkmanshipRating,
      timelinessDeliveryRating: feedbackData.ratings?.timelinessDeliveryRating,
      communicationStaffRating: feedbackData.ratings?.communicationStaffRating
    },
    npsScore,
    npsCategory,
    clientComments: feedbackData.clientComments || '',
    clientRepresentativeName: feedbackData.clientRepresentativeName || 'Client Representative',
    clientRepresentativeTitle: feedbackData.clientRepresentativeTitle || '',
    allowPublicMarketingShowcase: feedbackData.allowPublicMarketingShowcase !== undefined ? feedbackData.allowPublicMarketingShowcase : true,
    highlightQuoteForWebsite: feedbackData.highlightQuoteForWebsite || '',
    requiresManagementFollowUp: isDetractor,
    followUpActionTaken: feedbackData.followUpActionTaken || ''
  });

  let autoGeneratedComplaint = null;

  // Rule 3 Detractor Escalation
  if (isDetractor) {
    const complaintCode = await generateComplaintCode();
    const targetDate = new Date();
    targetDate.setHours(targetDate.getHours() + 24); // 24h SLA for detractor

    autoGeneratedComplaint = await CustomerComplaint.create({
      complaintCode,
      clientId: client._id,
      jobOrderId: jobOrder._id,
      siteInstallationId: feedbackData.siteInstallationId || null,
      reportedByClientContact: {
        fullName: feedback.clientRepresentativeName,
        phone: client.primaryPhone || '+251900000000',
        email: client.email || ''
      },
      category: 'installation_workmanship',
      severity: 'high_safety_or_electrical',
      status: 'logged_open',
      complaintSubject: `URGENT Detractor Escalation: Satisfaction Score ${overallScore}/5 on Job ${jobOrder.jobOrderNumber}`,
      detailedDescription: feedback.clientComments || 'Client reported critical dissatisfaction on completed installation. Immediate management investigation and corrective action required.',
      targetResolutionDate: targetDate,
      investigation: {
        siteVisitRequired: true,
        rootCauseFindings: 'Pending rapid-response field investigation'
      }
    });

    feedback.followUpActionTaken = `Automatically escalated to Management via high-priority Complaint ticket ${complaintCode}`;
    await feedback.save();
  }

  return { feedback, autoGeneratedComplaint };
};

