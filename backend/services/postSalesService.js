/**
 * 5. Resolve Complaint & Sign-Off
 */
export const resolveComplaint = async (complaintId, resolutionData, user) => {
  const complaint = await CustomerComplaint.findById(complaintId);
  if (!complaint) {
    const error = new Error(`Complaint not found with ID: ${complaintId}`);
    error.statusCode = 404;
    throw error;
  }

  let tech = resolutionData.correctiveAction?.assignedTechnician;
  if (!tech && user?.email) {
    const emp = await Employee.findOne({ email: user.email });
    if (emp) tech = emp._id;
  }

  complaint.correctiveAction = {
    assignedTechnician: tech || null,
    actionTakenSummary: resolutionData.correctiveAction?.actionTakenSummary || '',
    replacementPartsUsed: resolutionData.correctiveAction?.replacementPartsUsed || [],
    totalRepairCostETB: Number(resolutionData.correctiveAction?.totalRepairCostETB || 0),
    costAbsorbedBy: resolutionData.correctiveAction?.costAbsorbedBy || 'vector_warranty_reserve'
  };

  const actualResolved = resolutionData.actualResolvedDate ? new Date(resolutionData.actualResolvedDate) : new Date();
  complaint.actualResolvedDate = actualResolved;

  const diffHours = (actualResolved.getTime() - new Date(complaint.reportedDate).getTime()) / (1000 * 60 * 60);
  complaint.slaResolutionTimeHours = Number(Math.max(0, diffHours).toFixed(2));
  complaint.slaMet = actualResolved <= new Date(complaint.targetResolutionDate);

  if (resolutionData.resolutionSignOff) {
    complaint.resolutionSignOff = {
      clientConfirmedSatisfaction: Boolean(resolutionData.resolutionSignOff.clientConfirmedSatisfaction),
      confirmedByClientName: resolutionData.resolutionSignOff.confirmedByClientName || '',
      clientSignatureUrl: resolutionData.resolutionSignOff.clientSignatureUrl || '',
      confirmationDate: actualResolved,
      clientClosingRemarks: resolutionData.resolutionSignOff.clientClosingRemarks || '',
      completionEvidenceId: resolutionData.resolutionSignOff.completionEvidenceId || null
    };

    complaint.status = complaint.resolutionSignOff.clientConfirmedSatisfaction ? 'closed_satisfied' : 'resolved_pending_client_signoff';
  } else {
    complaint.status = resolutionData.status || 'resolved_pending_client_signoff';
  }

  await complaint.save();
  return complaint;
};

