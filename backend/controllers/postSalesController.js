import * as postSalesService from '../services/postSalesService.js';

// --- Customer Feedback ---

export const getCustomerFeedbacks = async (req, res) => {
  try {
    const feedbacks = await postSalesService.getCustomerFeedbacks(req.query);
    res.status(200).json({
      success: true,
      data: feedbacks
    });
  } catch (error) {
    res.status(error.statusCode || 500).json({
      success: false,
      message: error.message
    });
  }
};

export const createCustomerFeedback = async (req, res) => {
  try {
    const result = await postSalesService.recordCustomerFeedback(req.body, req.user);
    res.status(201).json({
      success: true,
      message: result.autoGeneratedComplaint
        ? 'Customer feedback submitted and detractor escalation ticket created'
        : 'Customer feedback submitted successfully',
      data: result
    });
  } catch (error) {
    res.status(error.statusCode || 400).json({
      success: false,
      message: error.message
    });
  }
};

